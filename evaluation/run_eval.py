"""Evaluation runner for the 10-case CrewAI maintenance report benchmark."""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

from agents.crew import MissingAPIKeyError, MissingModelError, run_monitoring_crew
from guardrails import verify_grounded_numbers

load_dotenv()

BASE_DIR = Path(__file__).resolve().parent.parent
DEFAULT_CASES_PATH = Path(__file__).resolve().parent / "test_cases.json"
DEFAULT_RESULTS_DIR = Path(os.environ.get("RESULTS_DIR", str(BASE_DIR / "results")))

ANOMALY_TERMS = (
    "anomaly",
    "anomalies",
    "anomalous",
    "spike",
    "drift",
    "flat-line",
    "flatline",
    "frozen",
    "fault",
    "elevated",
    "abnormal",
    "no anomalies",
)

GENERAL_ACTION_TERMS = (
    "inspect",
    "replace",
    "check",
    "clean",
    "flush",
    "lubricate",
    "align",
    "calibrate",
    "recalibrate",
    "torque",
    "reseat",
    "monitor",
    "schedule",
    "verify",
)


def evaluate_report_case(
    report_text: str,
    tool_outputs: list[str],
    expected_machine: str,
    expected_action_keywords: list[str],
) -> dict[str, Any]:
    """Score a single agent report against all 4 rubric criteria.

    Args:
        report_text: Final report generated by the agent crew.
        tool_outputs: Captured raw tool output strings from the run.
        expected_machine: Machine ID that must be referenced.
        expected_action_keywords: Domain-specific action keywords.

    Returns:
        Dictionary of individual check booleans and overall 'passed' boolean.
    """
    lowered = report_text.lower()
    machine_identified = expected_machine.lower() in lowered
    anomaly_mentioned = any(term in lowered for term in ANOMALY_TERMS)

    guardrail = verify_grounded_numbers(report_text=report_text, tool_outputs=tool_outputs)
    no_ungrounded_numbers = guardrail.passed

    action_terms = set(GENERAL_ACTION_TERMS) | {kw.lower() for kw in expected_action_keywords}
    sensible_action = any(term in lowered for term in action_terms)

    passed = all(
        [
            machine_identified,
            anomaly_mentioned,
            no_ungrounded_numbers,
            sensible_action,
        ]
    )
    return {
        "passed": passed,
        "checks": {
            "machine_identified": machine_identified,
            "anomaly_mentioned": anomaly_mentioned,
            "no_ungrounded_numbers": no_ungrounded_numbers,
            "sensible_action": sensible_action,
        },
        "ungrounded_numbers": guardrail.ungrounded_numbers,
        "guardrail_reason": guardrail.reason,
    }


def run_evaluation(
    cases_path: Path = DEFAULT_CASES_PATH,
    results_dir: Path | None = None,
) -> dict[str, Any]:
    """Run all 10 evaluation cases (retrying once on guardrail failure) and write results.

    Args:
        cases_path: Path to test_cases.json.
        results_dir: Output directory for agent_eval.json.

    Returns:
        Summary evaluation report dictionary.
    """
    cases: list[dict[str, Any]] = json.loads(cases_path.read_text(encoding="utf-8"))
    case_results: list[dict[str, Any]] = []
    passed_count = 0

    for case in cases:
        crew_res = run_monitoring_crew(
            machine_id=case["machine_id"],
            sensor=case["sensor"],
            notes=case.get("notes", ""),
            lookback_hours=int(case.get("lookback_hours", 500)),
            max_steps=5,
            timeout_seconds=60,
        )
        scored = evaluate_report_case(
            report_text=crew_res.report_text,
            tool_outputs=crew_res.tool_outputs,
            expected_machine=case["expected_machine"],
            expected_action_keywords=case.get("expected_action_keywords", []),
        )

        retried = False
        if not scored["checks"]["no_ungrounded_numbers"]:
            retried = True
            bad_nums = ", ".join(scored["ungrounded_numbers"]) or "none listed"
            retry_instruction = (
                "RETRY CORRECTION: Your previous report was rejected because it contained "
                f"ungrounded numbers not produced by any tool: {bad_nums}. "
                "Remove ALL of those ungrounded numbers and cite only numbers from tool outputs."
            )
            crew_res = run_monitoring_crew(
                machine_id=case["machine_id"],
                sensor=case["sensor"],
                notes=case.get("notes", ""),
                lookback_hours=int(case.get("lookback_hours", 500)),
                max_steps=5,
                timeout_seconds=60,
                extra_instruction=retry_instruction,
            )
            scored = evaluate_report_case(
                report_text=crew_res.report_text,
                tool_outputs=crew_res.tool_outputs,
                expected_machine=case["expected_machine"],
                expected_action_keywords=case.get("expected_action_keywords", []),
            )

        if scored["passed"]:
            passed_count += 1

        case_results.append(
            {
                "id": case["id"],
                "machine_id": case["machine_id"],
                "sensor": case["sensor"],
                "elapsed_seconds": crew_res.elapsed_seconds,
                "retried": retried,
                **scored,
                "report_preview": crew_res.report_text[:300],
            }
        )

    total = len(cases)
    pass_rate = round(passed_count / total, 4) if total > 0 else 0.0
    summary = {
        "total_cases": total,
        "passed_cases": passed_count,
        "pass_rate": pass_rate,
        "pass_rate_pct": round(pass_rate * 100.0, 2),
        "cases": case_results,
    }

    out_dir = results_dir or DEFAULT_RESULTS_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "agent_eval.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def main() -> None:
    """CLI entry point for running the 10-case agent evaluation."""
    try:
        summary = run_evaluation()
        print(
            f"Evaluation completed: {summary['passed_cases']}/{summary['total_cases']} "
            f"passed ({summary['pass_rate_pct']}%)."
        )
    except (MissingAPIKeyError, MissingModelError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
